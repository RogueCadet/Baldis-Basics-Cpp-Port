#!/usr/bin/env node
// bind-codegen.js -- generates src/bindings.cpp from the translated script headers:
//   - eng::makeScript(className)        factory (script classes derive Component/Singleton<T>)
//   - eng::bindScript(className,...)    dispatcher with one static binder per class
// Field mapping comes from member declarations in src/game/*.hpp (the translation keeps C#
// field names verbatim, so binder keys are exact). Binders fire only on PRESENT bake keys;
// absent keys keep the C++ default, which mirrors the C# initializer. Unity semantics intact.
//
// Usage: node tools/bind-codegen.js   (writes src/bindings.cpp)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const GAME = path.join(ROOT, 'src', 'game');
const OUT = path.join(ROOT, 'src', 'bindings.cpp');

const files = fs.readdirSync(GAME).filter(f => f.endsWith('.hpp')).sort();

// member-grammar (translation convention: exactly two-space indent, one declaration per line)
const declRe = /^  ([A-Za-z_][\w:, ]*?\*|\w[\w:]*)\s+(\w+)(?:\[(\d+)\])?\s*(?:=[^;]*)?;\s*(?:\/\/.*)?$/;
const structRe = /^struct\s+(\w+)\s*:\s*public\s+([A-Za-z_][A-Za-z0-9_]*(?:<\w+>)?)/;

// dedicated BindCtx channels for pointer kinds; everything else resolves via bindComp<T*>
const DIRECT_PTR = {
  'GameObject*': 'bindGameObject',
  'Transform*': 'bindTransformRef',
  'MeshRenderer*': 'bindMeshRendererRef', // Object-level node (DoorScript interior swap)
  'AudioClip*': 'bindAudioClip',
  'Material*': 'bindMaterial',
  'Sprite*': 'bindSprite',
  'Texture*': 'bindTexture',
  'UiText*': 'bindUiText',
};
// array channels by element kind (census: Transform*/AudioClip*/Sprite*/Texture*/int/RawImage*...)
const ARR_CHANNEL = {
  'Transform*': 'bindTrArray',
  'GameObject*': 'bindGOArray',
  'AudioClip*': 'bindClipArray',
  'Texture*': 'bindTexArray',
  'Sprite*': 'bindSprArray',
  'int': 'bindIntArray',
};
const VALUE_BIND = {
  'float': 'Float', 'int': 'Int', 'bool': 'Bool', 'std::string': 'String',
  'Vec3': 'Vec3', 'Vec2': 'Vec2', 'Color': 'Color',
};
const SKIP_KINDS = { 'Quat': true, 'RaycastHit': true, 'UnityEvent': true, 'Mat4': true };

// Template-argument spelling for bindComp<T>/bindCompArray<T>. Two corrections to the member's own
// declared type: (1) game/engine types live in namespace bb while the emitted binders live in
// namespace eng, so the name must be qualified (headers spell it bare, being inside namespace bb);
// (2) both helpers take the POINTEE as T (signatures `T*& out` / `T** out`, body dynamic_cast<T*>),
// so the declared pointer's star is stripped. "Foo*" -> "bb::Foo".
function qualElem(t) { return 'bb::' + t.replace(/\s*\*$/, ''); }

const classes = [];
for (const file of files) {
  const lines = fs.readFileSync(path.join(GAME, file), 'utf8').split(/\r?\n/);
  let cls = null;
  let prevLine = '';
  for (const line of lines) {
    const sm = line.match(structRe);
    if (sm) {
      const name = sm[1];
      const base = sm[2].split('<')[0];
      const isTemplate = /template\s*</.test(prevLine);
      // UnityAction adapters (BackCloseScreenAction, BasicOpenScreenAction) translate
      // `new UnityAction(Method)` delegates: they are not Components, are constructed by their
      // owner script in code, and never appear in a bake -- no factory, no binder.
      if (isTemplate || name === 'Singleton' || base === 'Coroutine' || base === 'UnityAction' ||
          /Anim$/.test(name)) {
        cls = null; // template base / coroutine subclass: no scene factory, no binder
      } else {
        cls = { name, file, members: [] };
        classes.push(cls);
      }
      prevLine = line;
      continue;
    }
    if (cls) {
      if (/^};/.test(line)) { cls = null; prevLine = line; continue; }
      if (/^struct /.test(line)) { cls = null; prevLine = line; continue; }
      const d = line.match(declRe);
      if (d) {
        const type = d[1].trim();
        const name = d[2];
        const arrLen = d[3] ? parseInt(d[3], 10) : 0;
        if (/^static/.test(type) || SKIP_KINDS[type]) { prevLine = line; continue; }
        cls.members.push({ type, name, arrLen });
      }
    }
    prevLine = line;
  }
}

const out = [];
out.push('// bindings.cpp -- GENERATED by tools/bind-codegen.js from src/game/*.hpp member');
out.push('// declarations. Script field binding for the bake loader: per-class static binders with');
out.push('// Unity serialization resolution ({fileID:0} = null; absent keys keep the C++ default).');
out.push('// Regenerate: node tools/bind-codegen.js');
out.push('#include "eng-internal.h"');
out.push('');
for (const file of files) out.push(`#include "game/${file}"`);
out.push('');
out.push('namespace eng {');
out.push('');

let memberCount = 0;
for (const cls of classes) {
  const body = [];
  for (const m of cls.members) {
    memberCount++;
    const key = m.name;
    const isArr = m.arrLen > 0;
    if (m.type.endsWith('*')) {
      if (m.type === 'Renderer*') { // BullyScript pointer-only field; MeshRenderer nodes are not
        // Renderer-derived, so scene refs cannot type-cast -- stays null (never dereferenced)
        body.push(`  // skipped ${key} (${m.type}): identity-only, unused in logic`);
        continue;
      }
      if (isArr) {
        const chan = ARR_CHANNEL[m.type] || 'compArrayWithCtx';
        if (chan === 'compArrayWithCtx') {
          body.push(`  ctx.bindCompArray<${qualElem(m.type)}>(f, "${key}", s->${key}, ${m.arrLen});`);
        } else {
          body.push(`  ctx.${chan}(f, "${key}", s->${key}, ${m.arrLen});`);
        }
        continue;
      }
      const chan = DIRECT_PTR[m.type];
      if (chan) {
        body.push(`  ctx.${chan}(f, "${key}", s->${key});`);
      } else {
        body.push(`  ctx.bindComp<${qualElem(m.type)}>(f, "${key}", s->${key});`);
      }
      continue;
    }
    const kind = VALUE_BIND[m.type];
    if (!kind) {
      body.push(`  // skipped ${key} (${m.type}): non-serialized kind (runtime state / enum)`);
      continue;
    }
    if (isArr) {
      // census shows no value-kind arrays except int[]; guard default covers future kinds
      const chan = (m.type === 'int') ? 'bindIntArray' : null;
      if (chan) body.push(`  ctx.${chan}(f, "${key}", s->${key}, ${m.arrLen});`);
      else body.push(`  // skipped ${key} (${m.type}[${m.arrLen}]): no value-array channel`);
      continue;
    }
    body.push(`  ctx.bind${kind}(f, "${key}", s->${key});`);
  }
  out.push(`// ${cls.name} (${cls.file})`);
  out.push(`static void bind_${cls.name}(bb::${cls.name}* s, const eng::JsonValue& f, eng::BindCtx& ctx) {`);
  if (body.length === 0) out.push('  (void)f; (void)ctx; (void)s; // no serialized members');
  out.push(...body);
  out.push('}');
  out.push('');
}

out.push('bb::Component* makeScript(const std::string& className) {');
for (const cls of classes) {
  out.push(`  if (className == "${cls.name}") return new bb::${cls.name}();`);
}
out.push('  return 0;');
out.push('}');
out.push('');
out.push('void bindScript(const std::string& className, bb::Component* c, const JsonValue& f, BindCtx& ctx) {');
for (const cls of classes) {
  out.push(`  if (className == "${cls.name}") {`);
  out.push(`    bind_${cls.name}(static_cast<bb::${cls.name}*>(c), f, ctx);`);
  out.push('    return;');
  out.push('  }');
}
out.push('}');
out.push('');
out.push('} // namespace eng');
out.push('');

fs.writeFileSync(OUT, out.join('\n'));
const factCount = classes.length;
console.log(`bindings.cpp: ${factCount} classes, ${memberCount} member bind calls emitted`);
